// Код темы (аркан 1–22) — у каждой темы своя точка матрицы
export function topicCode(key, { d, m, y }) {
  const sum = (n) => String(n).split('').reduce((s, x) => s + Number(x), 0);
  const a = reduce22(d);
  const b = m;
  const c = reduce22(sum(y));
  const dd = reduce22(a + b + c);
  const e = reduce22(a + b + c + dd);
  return {
    money: reduce22(b + dd),
    love: reduce22(a + dd),
    purpose: e,
    career: reduce22(a + c),
    anxiety: reduce22(b + c + dd),
    energy: dd,
    scale: reduce22(e + c),
  }[key];
}

